"""
На память - схема разделения Хоара. Используется в сортировке quick selection - алгоритмом быстрого выбора (задача 215)
Она защищает от дубликатов в массиве и не дает LTE в leetcode
"""
import random

def hoare_partition(nums: list[int], left: int, right: int) -> int:
    """
    Разделяет подмассив nums[left...right] на две части встречными указателями.
    Все элементы в левой части (до возвращаемого индекса j) будут <= pivot.
    Все элементы в правой части (после j) будут >= pivot.
    Возвращает индекс j — ГРАНИЦУ разделения двух лагерей.
    """
    # [Граница 1: Выбор пивота] Берем случайное значение элемента.
    # Сам изначальный индекс pivot_idx нам больше не важен — пивот может двигаться.
    pivot = nums[random.randint(left, right)]
    
    # [Граница 2: Инициализация указателей за пределами диапазона]
    # Мы сдвигаем их на 1 шаг наружу, так как в цикле используется 
    # паттерн do-while (сначала сдвиг, потом проверка).
    i = left - 1
    j = right + 1
    
    # [Граница 3: Бесконечный цикл встречного сканирования]
    while True:
        # Двигаем левый указатель вправо, пока элементы строго меньше pivot.
        # Он гарантированно остановится на элементе >= pivot.
        i += 1
        while nums[i] < pivot:
            i += 1
            
        # Двигаем правый указатель влево, пока элементы строго больше pivot.
        # Он гарантированно остановится на элементе <= pivot.
        j -= 1
        while nums[j] > pivot:
            j -= 1
            
        # [Граница 4: Точка встречи указателей]
        # Если указатели встретились или пересеклись, значит, вся область проверена.
        # Индекс j делит массив на две корректные зоны.
        if i >= j:
            return j  # Возвращаем финальную границу левой зоны
            
        # [Граница 5: Обмен нарушителей]
        # Если мы дошли сюда, значит nums[i] >= pivot, а nums[j] <= pivot.
        # Они стоят не в своих половинах. Меняем их местами и продолжаем поиск.
        nums[i], nums[j] = nums[j], nums[i]
