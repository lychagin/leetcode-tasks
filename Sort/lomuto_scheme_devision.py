"""
На память - схема разделения Ломуто. Используется в сортировке quick selection - алгоритмом быстрого выбора (задача 215)
"""

import random

def lomuto_partition(nums: list[int], left: int, right: int) -> int:
    """
    Разделяет подмассив nums[left...right] относительно опорного элемента.
    Все элементы <= pivot окажутся слева, все элементы > pivot — справа.
    Возвращает финальный ТОЧНЫЙ индекс, на который встал pivot.
    """
    # [Граница 1: Выбор пивота] Случайный выбор защищает от худшего случая O(N^2)
    pivot_idx = random.randint(left, right)
    pivot = nums[pivot_idx]
    
    # [Граница 2: Изоляция пивота] Убираем его в самый конец, чтобы не мешал
    nums[pivot_idx], nums[right] = nums[right], nums[pivot_idx]
    
    # [Граница 3: Зона накопления меньших элементов]
    # store_idx — это указатель на ПЕРВЫЙ элемент, который БОЛЬШЕ или РАВЕН pivot.
    # До этого указателя (слева от него) все элементы гарантированно МЕНЬШЕ pivot.
    store_idx = left
    
    # [Граница 4: Сканирование диапазона] Бежим от left до right-1 (пивот на right не трогаем)
    for i in range(left, right):
        if nums[i] < pivot:
            # Нашли элемент меньше пивота — закидываем его в левую зону
            nums[i], nums[store_idx] = nums[store_idx], nums[i]
            store_idx += 1  # Сдвигаем границу левой зоны вправо
            
    # [Граница 5: Финал] Возвращаем пивот из "изоляции" на его законное место.
    # Меняем его местами с первым элементом, который больше или равен ему.
    nums[store_idx], nums[right] = nums[right], nums[store_idx]
    
    # store_idx теперь — это финальная, железная позиция пивота в отсортированном массиве
    return store_idx
